def test_every_element_class(tmp_path):
    lat, rep = read_text(tmp_path, """
d: drift, l = 0.5
pp: pipe, l = 0.1
mon: monitor, l = 0.2
inst: instrument, l = 0.2
mk: marker
q: quadrupole, l = 0.6, k1 = 1
sx: sextupole, l = 0.6, k2 = 2
oc: octupole, l = 0.6, k3 = 3
mp: multipole, k1l = 0.02, k1sl = 0.03
ab: ab_multipole, b2 = 0.15, a1 = 0.03
bs: sbend, l = 0.8, angle = 0.08, e1 = 0.01, e2 = 0.02, fint = 0.5, hgap = 0.03, ref_tilt = 0.1
br: rbend, l = 0.8, angle = 0.08, e1 = 0.01, e2 = 0.02
sol: solenoid, l = 0.3, ks = 0.5
lc: lcavity, l = 0.5, voltage = 1e6, phi0 = -0.0833333333333333, rf_frequency = 325e6, n_cell = 1
hk: hkicker, l = 0.1, kick = 0.004
vk: vkicker, l = 0.1, kick = 0.005
kk: kicker, l = 0.1, hkick = 0.001, vkick = 0.002
rc: rcollimator, l = 0.1, x_limit = 0.02, y_limit = 0.03
ec: ecollimator, l = 0.1, x_limit = 0.02, y_limit = 0.03
fl: foil, material_type = "C", thickness = 1e-4, area_density = 0.237
ty: taylor, l = 0.5, {1: 0.5|1}, {2: 0.25|}
pa: patch, x_offset = 0.001, y_pitch = 0.002, tilt = 0.3
l1: line = (d, pp, mon, inst, mk, q, sx, oc, mp, ab, bs, br, sol, lc, hk, vk, kk, rc, ec, fl, ty, pa)
use, l1
""")
    e = lat.elements
    b = brho(lat)
    assert isinstance(e["d"], Drift) and isinstance(e["pp"], Drift)
    assert isinstance(e["mon"], Instrument) and e["mon"].family == "BPM"
    assert isinstance(e["inst"], Instrument) and e["inst"].family == "INSTRUMENT"
    assert isinstance(e["mk"], Marker)
    assert isinstance(e["q"], Quadrupole) and e["q"].multipole.Bn[1] == pytest.approx(1.0 * b)
    assert isinstance(e["sx"], Sextupole) and e["sx"].multipole.Bn[2] == pytest.approx(2.0 * b)
    assert isinstance(e["oc"], Octupole) and e["oc"].multipole.Bn[3] == pytest.approx(3.0 * b)
    # k{n}l / k{n}sl are exactly MAD-X's knl / ksl (verified engine-to-engine)
    assert isinstance(e["mp"], Multipole)
    assert e["mp"].multipole.BnL[1] == pytest.approx(0.02 * b)
    assert e["mp"].multipole.BsL[1] == pytest.approx(0.03 * b)
    # ab_multipole: b_n = k_nl / n!, a_n = k_nsl / n!  (measured with Tao)
    assert e["ab"].multipole.BnL[2] == pytest.approx(0.15 * 2 * b)
    assert e["ab"].multipole.BsL[1] == pytest.approx(0.03 * b)
    assert isinstance(e["bs"], Bend)
    assert e["bs"].length == pytest.approx(0.8)
    assert (e["bs"].bend.e1, e["bs"].bend.e2) == pytest.approx((0.01, 0.02))
    assert e["bs"].bend.edge_int1 == 0.5 and e["bs"].bend.edge_int2 is None
    assert e["bs"].bend.hgap == pytest.approx(0.03)
    assert e["bs"].bend.tilt_ref == pytest.approx(0.1)
    # rbend: `l` is the chord and Bmad shifts the pole faces by angle/2 itself
    assert e["br"].bend.rect is True
    assert e["br"].length == pytest.approx(0.8 * 0.04 / math.sin(0.04))
    assert (e["br"].bend.e1, e["br"].bend.e2) == pytest.approx((0.01 + 0.04, 0.02 + 0.04))
    assert isinstance(e["sol"], Solenoid) and e["sol"].solenoid.Bsol_T == pytest.approx(0.5 * b)
    assert isinstance(e["lc"], RFCavity)
    assert e["lc"].rf.voltage_V == 1e6
    assert e["lc"].rf.phase_rad == pytest.approx(-math.pi / 6)
    assert e["lc"].rf.frequency_Hz == 325e6 and e["lc"].rf.n_cell == 1
    assert isinstance(e["hk"], Kicker) and e["hk"].hkick == pytest.approx(0.004)
    assert e["vk"].vkick == pytest.approx(0.005)
    assert (e["kk"].hkick, e["kk"].vkick) == pytest.approx((0.001, 0.002))
    assert isinstance(e["rc"], Collimator) and e["rc"].aperture.shape == "RECTANGULAR"
    assert e["rc"].aperture.half_x == pytest.approx(0.02)
    assert e["ec"].aperture.shape == "ELLIPTICAL"       # Bmad's ecollimator default
    assert isinstance(e["fl"], Foil) and e["fl"].material == "C"
    assert e["fl"].thickness_kg_per_m2 == pytest.approx(0.237)
    assert isinstance(e["ty"], Taylor)
    assert e["ty"].matrix[0][0] == pytest.approx(0.5) and e["ty"].offset[1] == pytest.approx(0.25)
    assert isinstance(e["pa"], Patch)
    assert (e["pa"].x_offset, e["pa"].y_rot, e["pa"].tilt) == pytest.approx((0.001, 0.002, 0.3))
    assert rep.counts.get("DROPPED", 0) == 0


