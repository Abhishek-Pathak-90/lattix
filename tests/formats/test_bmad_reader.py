def test_species_and_energy_sources(tmp_path):
    lat, _ = read_text(tmp_path, "d: drift, l=1\nl1: line = (d)\nuse, l1\n")
    assert lat.reference.species.name == "proton"

    p = tmp_path / "p0c.bmad"
    p.write_text("parameter[particle] = #1H-\nparameter[p0c] = 1e9\n"
                 "d: drift, l=1\nl1: line = (d)\nuse, l1\n")
    lat, _ = Reader().read(p)
    assert lat.reference.species.name == "h-"
    assert lat.reference.pc_eV == pytest.approx(1e9)

    # Bmad's own default reference species is POSITRON (measured with Tao)
    p = tmp_path / "def.bmad"
    p.write_text("parameter[e_tot] = 1e6\nd: drift, l=1\nl1: line = (d)\nuse, l1\n")
    lat, _ = Reader().read(p)
    assert lat.reference.species.name == "positron"

    # caller overrides win
    lat, _ = Reader().read(p, species="electron", kinetic_energy_eV=5e6)
    assert lat.reference.species.name == "electron"
    assert lat.reference.kinetic_energy_eV == 5e6


