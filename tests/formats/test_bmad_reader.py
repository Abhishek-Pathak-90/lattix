def test_local_rigidity_is_used_through_an_lcavity(tmp_path):
    """Bmad's reference energy follows lcavity, so k1 must be converted locally."""
    lat, _ = read_text(tmp_path, """
q1: quadrupole, l = 0.1, k1 = 1
c1: lcavity, l = 0.5, voltage = 5e8, phi0 = 0, rf_frequency = 325e6
q2: quadrupole, l = 0.1, k1 = 1
l1: line = (q1, c1, q2)
use, l1
""")
    walk = propagate(lat)
    assert walk[-1].ref_out.kinetic_energy_eV == \
        pytest.approx(lat.reference.kinetic_energy_eV + 5e8)
    b_in = walk[0].ref_in.brho_signed
    b_out = walk[2].ref_in.brho_signed
    assert b_out > b_in
    assert lat.elements["q1"].multipole.Bn[1] == pytest.approx(b_in)
    assert lat.elements["q2"].multipole.Bn[1] == pytest.approx(b_out)


