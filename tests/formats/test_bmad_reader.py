def test_templates_and_attribute_overrides(tmp_path):
    lat, _ = read_text(tmp_path, """
q0: quadrupole, l = 0.6, k1 = 1, tilt
q1: q0, k1 = 2
q2: q0
l1: line = (q1, q2)
use, l1
q2[l] = 0.4
""")
    q1, q2 = lat.elements["q1"], lat.elements["q2"]
    assert isinstance(q1, Quadrupole) and isinstance(q2, Quadrupole)
    assert q1.length == pytest.approx(0.6)
    assert q1.multipole.Bn[1] == pytest.approx(2.0 * brho(lat))
    assert q2.multipole.Bn[1] == pytest.approx(1.0 * brho(lat))
    assert q2.length == pytest.approx(0.4)            # override applied after `use`
    # a bare `tilt` flag is Bmad's pi/(2(n+1)) default, inherited by both children
    assert q1.multipole.tilt[1] == pytest.approx(math.pi / 4)


def test_bare_tilt_defaults_per_order(tmp_path):
    lat, _ = read_text(tmp_path, """
q: quadrupole, l = 0.1, k1 = 1, tilt
s: sextupole, l = 0.1, k2 = 1, tilt
o: octupole, l = 0.1, k3 = 1, tilt
m: multipole, k1l = 1, t1, k3l = 2, t3
l1: line = (q, s, o, m)
use, l1
""")
    assert lat.elements["q"].multipole.tilt[1] == pytest.approx(math.pi / 4)
    assert lat.elements["s"].multipole.tilt[2] == pytest.approx(math.pi / 6)
    assert lat.elements["o"].multipole.tilt[3] == pytest.approx(math.pi / 8)
    # t1 = pi/4 makes the order-1 multipole purely skew
    m = lat.elements["m"]
    assert m.multipole.BnL.get(1, 0.0) == pytest.approx(0.0, abs=1e-12 * abs(brho(lat)))
    assert m.multipole.BsL[1] == pytest.approx(-1.0 * brho(lat))


