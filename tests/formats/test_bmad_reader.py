HEADER = """
parameter[particle] = proton
parameter[e_tot] = 1738272000
parameter[geometry] = open
"""


def read_text(tmp_path: Path, body: str, name: str = "deck.bmad", **kw):
    p = tmp_path / name
    p.write_text(HEADER + body)
    return Reader().read(p, **kw)


def brho(lat) -> float:
    return lat.reference.brho_signed


# ---------------------------------------------------------------- lexer
def test_strip_comment_honours_quotes():
    assert strip_comment('a: foil, material_type = "C!u" ! trailing') == \
        'a: foil, material_type = "C!u" '
    assert strip_comment("! whole line") == ""


def test_logical_lines_join_continuations():
    text = ("a: quadrupole, l = 1,\n   k1 = 2\n"          # trailing comma
            "b: drift, l = &\n  3\n"                       # ampersand
            "c: line = (a,\n   b)\n"                       # open bracket
            "d: drift, l = 4\n   , tilt = 0.1\n")          # begin-line comma
    got = [t for t, _ in logical_lines(text)]
    assert got == ["a: quadrupole, l = 1, k1 = 2", "b: drift, l = 3",
                   "c: line = (a, b)", "d: drift, l = 4 , tilt = 0.1"]


def test_split_statements_and_top_level():
    assert split_statements("a: drift, l=1; b: marker") == ["a: drift, l=1", "b: marker"]
    assert split_top("l = 1, grid = {a, b}, t = 2") == ["l = 1", "grid = {a, b}", "t = 2"]
    # a semicolon inside a quoted string is not a separator
    assert split_statements('a: foil, material_type = "C;u"') == ['a: foil, material_type = "C;u"']


